def convert_markdown_to_pdf(
    md_content: str,
    output_pdf_path: str,
    title: str = "Technical Specification",
    footer_text: str = "BlackSheep Engineering Architecture | Indian Railways",
    page_size=letter
):
    """
    Converts markdown content to a styled PDF file.
    """
    os.makedirs(os.path.dirname(os.path.abspath(output_pdf_path)), exist_ok=True)
    
    doc = SimpleDocTemplate(
        output_pdf_path,
        pagesize=page_size,
        leftMargin=54,  # 0.75 in
        rightMargin=54,
        topMargin=54,
        bottomMargin=54
    )

    page_width, page_height = page_size
    printable_width = page_width - 108

    styles = get_pdf_styles()
    flowables = parse_markdown_to_flowables(md_content, styles, max_width=printable_width)

    # Custom canvas maker carrying doc metadata
    def canvas_maker(*args, **kwargs):
        c = NumberedCanvas(*args, **kwargs)
        c.doc_title = title
        c.doc_footer = footer_text
        return c

    doc.build(flowables, canvasmaker=canvas_maker)
    print(f"[ToPDF] Successfully generated PDF: '{output_pdf_path}' ({os.path.getsize(output_pdf_path):,} bytes)")
    return output_pdf_path

def convert_file_to_pdf(
    input_file_path: str,
    output_pdf_path: str = None,
    title: str = None,
    footer_text: str = "BlackSheep Engineering Architecture | Indian Railways"
):
    """
    Reads markdown or text from input_file_path and produces output_pdf_path.
    """
    if not os.path.exists(input_file_path):
        raise FileNotFoundError(f"Input file not found: '{input_file_path}'")

    with open(input_file_path, 'r', encoding='utf-8') as f:
        content = f.read()

    if output_pdf_path is None:
        base, _ = os.path.splitext(input_file_path)
        output_pdf_path = base + ".pdf"

    if title is None:
        # Infer title from first H1 if available
        for line in content.split('\n'):
            line = line.strip()
            if line.startswith('# '):
                title = line[2:].strip()
                break
        if not title:
            title = os.path.splitext(os.path.basename(input_file_path))[0].replace('_', ' ').title()

    return convert_markdown_to_pdf(content, output_pdf_path, title=title, footer_text=footer_text)


