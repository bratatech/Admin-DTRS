# 3. MARKDOWN TO REPORTLAB FLOWABLES PARSER
# ----------------------------------------------------------------------

def escape_xml_text(text):
    """Safely escape text while preserving basic formatting tags"""
    # Replace & first
    text = text.replace('&', '&amp;')
    text = text.replace('<', '&lt;').replace('>', '&gt;')
    
    # Restore bold & italics from markdown
    # Convert `code` to <font name="Courier">code</font>
    text = re.sub(r'`([^`]+)`', r'<font name="Courier" color="#805AD5"><b>\1</b></font>', text)
    # Convert **bold** to <b>bold</b>
    text = re.sub(r'\*\*([^*]+)\*\*', r'<b>\1</b>', text)
    # Convert *italic* to <i>italic</i>
    text = re.sub(r'(?<!\*)\*([^*]+)\*(?!\*)', r'<i>\1</i>', text)
    
    # Re-allow basic tags
    text = text.replace('&lt;b&gt;', '<b>').replace('&lt;/b&gt;', '</b>')
    text = text.replace('&lt;i&gt;', '<i>').replace('&lt;/i&gt;', '</i>')
    text = text.replace('&lt;font', '<font').replace('&lt;/font&gt;', '</font>')
    text = text.replace('&quot;', '"')
    return text

def parse_markdown_to_flowables(md_text, styles, max_width=504):
    flowables = []
    lines = md_text.split('\n')
    i = 0
    n = len(lines)

    in_code_block = False
    code_lines = []

    while i < n:
        line = lines[i]
        raw_line = line.strip()

        # Handle Code Block
        if raw_line.startswith('```'):
            if in_code_block:
                # End of code block
                code_text = "<br/>".join([escape_xml_text(cl).replace(' ', '&nbsp;') for cl in code_lines])
                p = Paragraph(code_text, styles['CodeBlock'])
                t = Table([[p]], colWidths=[max_width])
                t.setStyle(TableStyle([
                    ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor("#EDF2F7")),
                    ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E0")),
                    ('TOPPADDING', (0, 0), (-1, -1), 6),
                    ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
                    ('LEFTPADDING', (0, 0), (-1, -1), 8),
                    ('RIGHTPADDING', (0, 0), (-1, -1), 8),
                ]))
                flowables.append(t)
                flowables.append(Spacer(1, 4))
                in_code_block = False
                code_lines = []
            else:
                in_code_block = True
                code_lines = []
            i += 1
            continue

        if in_code_block:
            code_lines.append(line)
            i += 1
            continue

        # Blank Line
        if not raw_line:
            i += 1
            continue

        # Horizontal Rule
        if re.match(r'^(---+|\*\*\*+|___+)$', raw_line):
            flowables.append(HRFlowable(width="100%", thickness=0.75, color=colors.HexColor("#CBD5E0"), spaceBefore=6, spaceAfter=8))
            i += 1
            continue

        # Markdown Table Detection
        if raw_line.startswith('|') and raw_line.endswith('|'):
            table_lines = []
            while i < n and lines[i].strip().startswith('|') and lines[i].strip().endswith('|'):
                table_lines.append(lines[i].strip())
                i += 1

            if len(table_lines) >= 2:
                # Parse headers
                raw_headers = [c.strip() for c in table_lines[0].split('|')[1:-1]]
                num_cols = len(raw_headers)
                
                # Check for separator line (| :--- | :--- |)
                data_start_idx = 1
                if len(table_lines) > 1 and re.match(r'^[|\s:-]+$', table_lines[1]):
                    data_start_idx = 2

                table_data = []
                # Header row
                header_row = [Paragraph(escape_xml_text(h), styles['TableHeader']) for h in raw_headers]
                table_data.append(header_row)

                # Data rows
                for row_line in table_lines[data_start_idx:]:
                    cols = [c.strip() for c in row_line.split('|')[1:-1]]
                    # Pad or truncate to match num_cols
                    while len(cols) < num_cols:
                        cols.append('')
                    cols = cols[:num_cols]
                    data_row = [Paragraph(escape_xml_text(c), styles['TableCell']) for c in cols]
                    table_data.append(data_row)

                # Calculate balanced column widths
                col_width = max_width / num_cols
                col_widths = [col_width] * num_cols

                # Refine widths based on content lengths if possible
                if num_cols == 2:
                    col_widths = [max_width * 0.35, max_width * 0.65]
                elif num_cols == 3:
                    col_widths = [max_width * 0.25, max_width * 0.35, max_width * 0.40]
                elif num_cols == 4:
                    col_widths = [max_width * 0.20, max_width * 0.25, max_width * 0.25, max_width * 0.30]

                table = Table(table_data, colWidths=col_widths, repeatRows=1)
                t_style = [
                    ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#1A365D")),
                    ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
                    ('ALIGN', (0, 0), (-1, -1), 'LEFT'),
                    ('VALIGN', (0, 0), (-1, -1), 'TOP'),
                    ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E0")),
                    ('TOPPADDING', (0, 0), (-1, -1), 4),
                    ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
                    ('LEFTPADDING', (0, 0), (-1, -1), 5),
                    ('RIGHTPADDING', (0, 0), (-1, -1), 5),
                ]
                # Alternating row colors
                for r in range(1, len(table_data)):
                    bg = colors.HexColor("#F7FAFC") if r % 2 == 1 else colors.white
                    t_style.append(('BACKGROUND', (0, r), (-1, r), bg))

                table.setStyle(TableStyle(t_style))
                flowables.append(table)
                flowables.append(Spacer(1, 6))
            continue

        # Headings
        if raw_line.startswith('# '):
            flowables.append(Paragraph(escape_xml_text(raw_line[2:]), styles['DocTitle']))
            i += 1
            continue
        elif raw_line.startswith('## '):
            flowables.append(Paragraph(escape_xml_text(raw_line[3:]), styles['CustomH1']))
            i += 1
            continue
        elif raw_line.startswith('### '):
            flowables.append(Paragraph(escape_xml_text(raw_line[4:]), styles['CustomH2']))
            i += 1
            continue
        elif raw_line.startswith('#### '):
            flowables.append(Paragraph(escape_xml_text(raw_line[5:]), styles['CustomH3']))
            i += 1
            continue

        # Blockquote / Callout (> [!NOTE] or > text)
        if raw_line.startswith('>'):
            callout_text = raw_line[1:].strip()
            # If multiple blockquote lines exist, collect them
            bq_lines = [callout_text]
            while i + 1 < n and lines[i + 1].strip().startswith('>'):
                i += 1
                bq_lines.append(lines[i].strip()[1:].strip())
            
            combined_bq = " ".join(bq_lines)
            combined_bq = re.sub(r'^\[!(NOTE|TIP|IMPORTANT|WARNING|CAUTION)\]\s*', r'<b>[\1]</b> ', combined_bq)
            p = Paragraph(escape_xml_text(combined_bq), styles['Callout'])
            callout_box = Table([[p]], colWidths=[max_width])
            callout_box.setStyle(TableStyle([
                ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor("#EBF8FF")),
                ('LINELEFT', (0, 0), (-1, -1), 3.0, colors.HexColor("#2B6CB0")),
                ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor("#BEE3F8")),
                ('TOPPADDING', (0, 0), (-1, -1), 5),
                ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
                ('LEFTPADDING', (0, 0), (-1, -1), 8),
                ('RIGHTPADDING', (0, 0), (-1, -1), 8),
            ]))
            flowables.append(callout_box)
            flowables.append(Spacer(1, 5))
            i += 1
            continue

        # Bullet List (- or *)
        if re.match(r'^[\*\-]\s+', raw_line):
            bullet_content = re.sub(r'^[\*\-]\s+', '', raw_line)
            p = Paragraph(f"&bull;&nbsp;&nbsp;{escape_xml_text(bullet_content)}", styles['CustomBullet'])
            flowables.append(p)
            i += 1
            continue

        # Numbered List (1. ...)
        m_num = re.match(r'^(\d+)\.\s+', raw_line)
        if m_num:
            num_str = m_num.group(1)
            num_content = raw_line[len(m_num.group(0)):]
            p = Paragraph(f"<b>{num_str}.</b>&nbsp;&nbsp;{escape_xml_text(num_content)}", styles['CustomBullet'])
            flowables.append(p)
            i += 1
            continue

        # Standard Body Paragraph
        flowables.append(Paragraph(escape_xml_text(raw_line), styles['CustomBody']))
        i += 1

    return flowables


