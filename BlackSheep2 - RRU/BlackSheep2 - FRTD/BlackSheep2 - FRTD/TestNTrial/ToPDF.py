"""
ToPDF.py
========
A generic, automated Markdown & text-to-PDF converter using ReportLab.
Converts markdown reports, technical documentation, tables, and architectural specifications
into high-quality, beautifully styled publication-grade PDFs with custom headers, footers,
and two-pass page numbering ("Page X of Y").

Usage:
    CLI:
        python ToPDF.py input.md -o output.pdf [--title "Document Title"] [--author "Author"]
        python ToPDF.py --content "# Title\nSome content" -o output.pdf

    Python:
        from ToPDF import convert_markdown_to_pdf, convert_file_to_pdf
        convert_file_to_pdf("documentation.md", "documentation.pdf", title="My Report")
"""

import os
import sys
import re
import argparse
from reportlab.lib.pagesizes import letter, A4
from reportlab.lib import colors
from reportlab.lib.units import inch
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, KeepTogether, HRFlowable
)
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.pdfgen import canvas

# ----------------------------------------------------------------------
# 1. TWO-PASS CANVAS WITH HEADERS, FOOTERS & PAGE NUMBERS
# ----------------------------------------------------------------------

class NumberedCanvas(canvas.Canvas):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count):
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#718096"))
        page_width, page_height = self._pagesize

        # Running Header (pages > 1)
        if self._pageNumber > 1:
            header_text = getattr(self, 'doc_title', 'Technical Report')
            self.drawString(54, page_height - 36, header_text)
            self.setStrokeColor(colors.HexColor("#CBD5E0"))
            self.setLineWidth(0.5)
            self.line(54, page_height - 42, page_width - 54, page_height - 42)

        # Running Footer (all pages)
        footer_left = getattr(self, 'doc_footer', 'Generated by ToPDF')
        page_str = f"Page {self._pageNumber} of {page_count}"
        self.drawString(54, 34, footer_left)
        self.drawRightString(page_width - 54, 34, page_str)
        self.setStrokeColor(colors.HexColor("#E2E8F0"))
        self.setLineWidth(0.5)
        self.line(54, 46, page_width - 54, 46)

        self.restoreState()


